#!/usr/bin/env python3
"""verify_outputs.py - Check that a fresh run reproduces the archived results.

1. Structural checks (always):
     cleaned dataset    : 5216 rows
     featurized set     : 5207 compositions
     split sizes        : 3645 train / 1041 val / 521 test
2. Numerical checks (when reference/ holds the archived CSVs):
     every CSV found in reference/ is compared with the freshly generated file of the
     same name (tolerance 1e-9 on numeric columns).

Usage (from the project root):
    python scripts/verify_outputs.py
Exit code 0 = everything matches, 1 = at least one check failed.
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from tco_stability.paths import ensure_project_root
root = ensure_project_root()

import numpy as np
import pandas as pd

TOL = 1e-9
EXPECTED = {'cleaned_rows': 5216, 'train': 3645, 'val': 1041, 'test': 521}

# Where each archived file is regenerated by the pipeline
SEARCH_DIRS = ["data/processed", "data/splits", "results"]

failures = []


def check(label, ok, detail=""):
    print(f"  [{'OK' if ok else 'FAIL'}] {label} {detail}")
    if not ok:
        failures.append(label)


print("=" * 70)
print("STRUCTURAL CHECKS")
print("=" * 70)

cleaned = Path("data/processed/mp_doped_oxides_cleaned.csv")
if cleaned.exists():
    n = len(pd.read_csv(cleaned))
    check("cleaned dataset rows", n == EXPECTED['cleaned_rows'], f"({n} vs {EXPECTED['cleaned_rows']})")
else:
    check("cleaned dataset present", False, str(cleaned))

for split in ("train", "val", "test"):
    p = Path(f"data/splits/{split}.csv")
    if p.exists():
        n = len(pd.read_csv(p))
        check(f"{split} split size", n == EXPECTED[split], f"({n} vs {EXPECTED[split]})")
    else:
        check(f"{split} split present", False, str(p))

print("\n" + "=" * 70)
print("NUMERICAL COMPARISON WITH reference/")
print("=" * 70)

ref_dir = Path("reference")
ref_files = sorted(ref_dir.glob("*.csv")) if ref_dir.exists() else []
if not ref_files:
    print("  reference/ is empty: copy the archived CSVs there to enable this check.")

for ref in ref_files:
    new = next((Path(d) / ref.name for d in SEARCH_DIRS if (Path(d) / ref.name).exists()), None)
    if new is None:
        check(f"{ref.name} regenerated", False, "(not found in data/processed, data/splits or results)")
        continue
    a, b = pd.read_csv(ref), pd.read_csv(new)
    if a.shape != b.shape or list(a.columns) != list(b.columns):
        check(f"{ref.name}", False, f"(shape/columns differ: {a.shape} vs {b.shape})")
        continue
    ok = True
    for col in a.columns:
        if pd.api.types.is_numeric_dtype(a[col]):
            ok &= bool(np.allclose(a[col].values, b[col].values, rtol=0, atol=TOL, equal_nan=True))
        else:
            ok &= bool((a[col].astype(str).values == b[col].astype(str).values).all())
    check(f"{ref.name}", ok)

print("\n" + "=" * 70)
if failures:
    print(f"{len(failures)} CHECK(S) FAILED: {failures}")
    sys.exit(1)
print("ALL CHECKS PASSED")
sys.exit(0)
